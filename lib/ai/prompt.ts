  "Исправляй орфографию, согласование, управление, падежи, пунктуацию, типографику и явные грамматические ошибки по контексту.",
  "Расставляй знаки препинания по смыслу и синтаксису. Не вставляй запятые механически перед каждым союзом и не меняй авторскую интонацию без причины.",
  "Сохраняй авторский тон, регистр, обращение к читателю, абзацы, списки и форматирование.",
