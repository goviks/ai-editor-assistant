const MODE_INSTRUCTIONS: Record<AssistMode, string> = {
  improve:
    "Режим «Улучшить». Проведи полную вычитку: исправь ошибки, восстанови пропущенные знаки препинания, проверь строение и связь частей каждого предложения, согласование и грамматическое управление. Устраняй неясность и тяжёлые обороты только тогда, когда это можно сделать без изменения смысла. Убирай лишь очевидные случайные повторы и пустые слова; не превращай авторский текст в безличный канцелярский стиль. Сохрани все значимые мысли и детали. Не сокращай текст ради целевой метрики.",
  shorten:
    "Режим «Сократить». Сделай текст заметно компактнее за счёт повторов одной мысли, словесной избыточности и громоздких конструкций. Перестрой предложения, если так становится яснее, но заново проверь грамматические основы, связи частей и пунктуацию после перестройки. Сохрани ключевые утверждения, факты, имена, числа, даты, примеры, ограничения, отрицания и причинно-следственные связи. Не обрывай текст, не удаляй целые смысловые части только ради процента и не заменяй аргументы общим выводом. Если существенное сокращение повредит полноте или точности, сократи меньше.",
};

export function buildMessages(text: string, mode: AssistMode): ChatMessage[] {
  return [
    { role: "system", content: SYSTEM_PROMPT },
    {
      role: "user",
      content: [
        MODE_INSTRUCTIONS[mode],
        "",
        "Фрагмент (между маркерами):",
        "<<<",
        text,
        ">>>",
        "",
        "Отредактируй содержимое маркеров. Маркеры не входят в ответ.",
      ].join("\n"),
    },
  ];
}

export function maxInputChars(): number {
  const parsed = Number.parseInt(process.env.AI_MAX_INPUT_CHARS ?? "", 10);
  return Number.isFinite(parsed) && parsed > 0 ? parsed : 6000;
}
