import type { AssistMode } from "@/types/ai";

export interface ChatMessage {
  role: "system" | "user";
  content: string;
}

export const MODE_LABELS: Record<AssistMode, string> = {
  improve: "Улучшить",
  shorten: "Сократить",
};

